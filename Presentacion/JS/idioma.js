// Función para aplicar idioma
function aplicarIdioma(idioma) {
  localStorage.setItem("idioma", idioma);
  document.querySelectorAll("[data-trad]").forEach(el => {
    const key = el.getAttribute("data-trad");
    if(traducciones[idioma][key]) {
      // Si es input o textarea, cambiar placeholder
      if(el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = traducciones[idioma][key];
      } else {
        // Para todo el resto, usar innerHTML para soportar HTML
        el.innerHTML = traducciones[idioma][key];
      }
    }
  });
}

// Cambiar idioma al tocar el botón
const botonCambiarIdioma = document.getElementById("cambiarIdioma");
if(botonCambiarIdioma){
  botonCambiarIdioma.addEventListener("click", () => {
    const nuevoIdioma = (localStorage.getItem("idioma")==="es") ? "en" : "es";
    aplicarIdioma(nuevoIdioma);
  });
}

// Aplicar idioma al cargar la página
document.addEventListener("DOMContentLoaded", () => {
  const idiomaGuardado = localStorage.getItem("idioma") || "es";
  aplicarIdioma(idiomaGuardado);
});
